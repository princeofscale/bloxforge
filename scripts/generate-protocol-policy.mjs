#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(root, 'packages', 'core', 'src', 'protocol-endpoints.json');
const pluginOutputPath = join(root, 'studio-plugin', 'src', 'modules', 'generated', 'ProtocolPolicy.ts');
const coreOutputPath = join(root, 'packages', 'core', 'src', 'protocol-endpoints.generated.ts');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));

function validateEndpoints(value, label) {
  if (!Array.isArray(value) || value.some((endpoint) => typeof endpoint !== 'string' || !endpoint.startsWith('/api/'))) {
    throw new Error(`${label} must be an array of /api/ endpoint strings`);
  }
  if (new Set(value).size !== value.length) {
    throw new Error(`${label} contains duplicate endpoints`);
  }
}

validateEndpoints(source.read, 'read');
validateEndpoints(source.mutation, 'mutation');
validateEndpoints(source.heavy, 'heavy');
const all = new Set([...source.read, ...source.mutation]);
if (all.size !== source.read.length + source.mutation.length) {
  throw new Error('An endpoint cannot be both read and mutation');
}
for (const endpoint of source.heavy) {
  if (!all.has(endpoint)) throw new Error(`Heavy endpoint is not declared: ${endpoint}`);
}

const quote = (value) => JSON.stringify(value);
const pluginGenerated = `// Generated by scripts/generate-protocol-policy.mjs from
// packages/core/src/protocol-endpoints.json. Do not edit by hand.

export const INSPECTOR_ENDPOINTS = [
${source.read.map((endpoint) => `\t${quote(endpoint)},`).join('\n')}
] as const;

export type InspectorEndpoint = (typeof INSPECTOR_ENDPOINTS)[number];
`;

const coreGenerated = `// Generated by scripts/generate-protocol-policy.mjs from
// protocol-endpoints.json. Do not edit by hand.

export const ENDPOINT_SOURCE = ${JSON.stringify(source, null, 2)} as const;
`;

if (process.argv.includes('--check')) {
  const pluginCurrent = readFileSync(pluginOutputPath, 'utf8');
  const coreCurrent = readFileSync(coreOutputPath, 'utf8');
  if (pluginCurrent !== pluginGenerated || coreCurrent !== coreGenerated) {
    throw new Error('Generated protocol policy is stale. Run npm run protocol:generate.');
  }
} else {
  writeFileSync(pluginOutputPath, pluginGenerated, 'utf8');
  writeFileSync(coreOutputPath, coreGenerated, 'utf8');
  console.log(`Generated ${pluginOutputPath.slice(root.length + 1)}`);
  console.log(`Generated ${coreOutputPath.slice(root.length + 1)}`);
}
