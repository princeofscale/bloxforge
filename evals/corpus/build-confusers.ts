// Derives the 436-case confuser bucket from the positives and the catalog.
//
// Two per tool, as the roadmap specifies — but written by construction rather
// than by hand, and the reason matters. A hand-written "negative" is a query
// its author already believes is hard, which measures the author's intuition
// about the retriever. A confuser derived from nearest-neighbour distance is a
// query that is *actually* close in the space the retriever scores in, and it
// carries a gold answer that is already known-good because it is another tool's
// positive case.
//
// So for tool T with nearest neighbours N1 and N2, the two confusers are N1's
// and N2's own queries, asserting that T must not outrank them. If T wins one,
// that is a real collision between two tools an agent has to choose between.
//
// Output is checked in and frozen. Run `npx tsx evals/corpus/build-confusers.ts`
// to regenerate; `corpus-check.ts` fails if the checked-in file does not match
// what this produces, so the derivation cannot drift away from its inputs.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const require = createRequire(`${root}/`);

interface CatalogEntry { name: string; domain: string; mode: string; whenToUse: string }

const { buildCatalog } = require('./packages/core/dist/tools/tool-catalog.js');
const { TOOL_DEFINITIONS } = require('./packages/core/dist/tools/definitions.js');
const catalog: CatalogEntry[] = buildCatalog(TOOL_DEFINITIONS);

const positives = JSON.parse(readFileSync(`${here}/positives.json`, 'utf8')) as {
  cases: { tool: string; query: string }[];
};
const queryOf = new Map(positives.cases.map((c) => [c.tool, c.query]));

/** Content words of a tool, as a set — the space neighbours are measured in. */
function profile(e: CatalogEntry): Set<string> {
  return new Set(
    `${e.name.replace(/_/g, ' ')} ${e.whenToUse}`
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((w) => w.length >= 3),
  );
}

const profiles = new Map(catalog.map((e) => [e.name, profile(e)]));

function jaccard(a: Set<string>, b: Set<string>): number {
  let shared = 0;
  for (const w of a) if (b.has(w)) shared++;
  const union = a.size + b.size - shared;
  return union === 0 ? 0 : shared / union;
}

const cases: unknown[] = [];
for (const entry of catalog) {
  const mine = profiles.get(entry.name)!;
  const ranked = catalog
    .filter((other) => other.name !== entry.name)
    .map((other) => ({
      name: other.name,
      // Same domain first among equals: two scene readers are a choice an agent
      // actually faces, where a scene reader and a Wally command are not.
      score: jaccard(mine, profiles.get(other.name)!) + (other.domain === entry.domain ? 0.05 : 0),
    }))
    // Deterministic to the last tie: score, then name.
    .sort((a, b) => b.score - a.score || a.name.localeCompare(b.name));

  for (const neighbour of ranked.slice(0, 2)) {
    const query = queryOf.get(neighbour.name);
    if (!query) throw new Error(`no positive query for ${neighbour.name}`);
    cases.push({
      id: `conf_${entry.name}__${neighbour.name}`,
      query,
      gold: [neighbour.name],
      mustNotRankFirst: [entry.name],
      similarity: +neighbour.score.toFixed(3),
    });
  }
}

const out = {
  bucket: 'confuser',
  note: 'Generated by build-confusers.ts — do not hand-edit. Two per tool: the nearest-neighbour tool\'s own query, asserting this tool does not outrank it.',
  generatedFrom: { tools: catalog.length, positives: positives.cases.length },
  cases,
};

writeFileSync(`${here}/confusers.generated.json`, `${JSON.stringify(out, null, 1)}\n`);
console.error(`confusers: ${cases.length} cases from ${catalog.length} tools`);
